def get_stream_by_id(cam_id: str) -> Optional[Dict[str, Any]]:
    return CAMERA_STREAM_PROFILES.get(cam_id)

def get_ffmpeg_rtsp_command(cam_id: str, workspace_root: str) -> str:
    """
    Generate the exact FFmpeg command that re-broadcasts the Indian CCTV footage
    as a real RTSP stream to any RTSP server (like MediaMTX, RTSP Simple Server, etc.).
    """
    profile = CAMERA_STREAM_PROFILES.get(cam_id)
    if not profile:
        return ""
    
    rel_path = profile["footage"].lstrip("/")
    abs_footage = os.path.join(workspace_root, "frontend", "public", rel_path)
    rtsp_target = profile["rtsp_url"]
    
    # FFmpeg loop command
    return f"ffmpeg -re -stream_loop -1 -i \"{abs_footage}\" -c copy -f rtsp {rtsp_target}"
